export type GlyphName = keyof typeof GLYPHS;

/** Ink cells as [x, y] pairs, for drawing one SVG rect per pixel. */
export function cells(name: GlyphName): [number, number][] {
  const out: [number, number][] = [];
  GLYPHS[name].forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") out.push([x, y]);
  });
  return out;
}

/**
 * One SVG path for a glyph, merging each horizontal run of ink into a single rect.
 * Fewer nodes than a rect per pixel, and no hairline seams between neighbours.
 */
export function glyphPath(name: GlyphName): string {
  let d = "";
  GLYPHS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === "#") x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return d;
}
